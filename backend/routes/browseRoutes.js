const express=require('express');
const {authenticateToken}=require('../middleware/auth');
const c=require('../controllers/browseController');
const router=express.Router();
router.get('/categories',authenticateToken,c.categories);
router.get('/auctions',authenticateToken,c.list);
router.get('/auctions/:id',authenticateToken,c.detail);
router.get('/watchlist',(req,res,next)=>{req.watchlistOnly=true;next();},authenticateToken,c.list);
router.post('/watchlist',authenticateToken,c.save);
router.delete('/watchlist/:id',authenticateToken,c.remove);
const bidding=require('../controllers/biddingController');
router.post('/auctions/:id/bids',authenticateToken,bidding.place);
router.get('/auctions/:id/live',authenticateToken,bidding.stream);
const activity=require('../controllers/activityController');
router.get('/activity/bids',authenticateToken,activity.bids);
router.get('/activity/watchlist',authenticateToken,activity.watchlist);
router.get('/activity/results',authenticateToken,require('../controllers/resultsController').list);
module.exports=router;
